func TestUnboundProvider_Render_SkipsEmptyURL(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	endpoints := []*endpoint.Endpoint{
		{Name: "no-url", URL: "", Interval: "1m"},
		{Name: "valid", URL: "https://valid.example.com", Interval: "1m"},
	}

	data, err := p.Render(endpoints)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	content := string(data)
	if !strings.Contains(content, "valid.example.com") {
		t.Errorf("expected valid endpoint in output, got:\n%s", content)
	}
	if strings.Contains(content, "no-url") {
		t.Errorf("endpoint with empty URL should be skipped, got:\n%s", content)
	}
}

func TestUnboundProvider_Render_SortedAlphabetically(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	endpoints := []*endpoint.Endpoint{
		{Name: "z-app", URL: "https://z.example.com", Interval: "1m"},
		{Name: "a-app", URL: "https://a.example.com", Interval: "1m"},
		{Name: "m-app", URL: "https://m.example.com", Interval: "1m"},
	}

	data, err := p.Render(endpoints)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	content := string(data)
	aPos := strings.Index(content, "a.example.com")
	mPos := strings.Index(content, "m.example.com")
	zPos := strings.Index(content, "z.example.com")

	if aPos == -1 || mPos == -1 || zPos == -1 {
		t.Fatalf("expected all hostnames in output, got:\n%s", content)
	}

	if aPos >= mPos || mPos >= zPos {
		t.Errorf("records should be sorted alphabetically: a=%d m=%d z=%d\noutput:\n%s", aPos, mPos, zPos, content)
	}
}

func TestUnboundProvider_Render_TrailingDot(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	endpoints := []*endpoint.Endpoint{
		{Name: "app", URL: "https://app.example.com", Interval: "1m"},
	}

	data, err := p.Render(endpoints)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	// The hostname in the record must end with a dot (FQDN).
	if !strings.Contains(string(data), "app.example.com.") {
		t.Errorf("expected trailing dot in FQDN, got:\n%s", string(data))
	}
}

func TestUnboundProvider_Render_URLWithPort(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	endpoints := []*endpoint.Endpoint{
		{Name: "svc", URL: "tcp://svc.example.com:5432", Interval: "1m"},
	}

	data, err := p.Render(endpoints)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	content := string(data)
	// Port should not appear in the DNS record.
	if strings.Contains(content, ":5432") {
		t.Errorf("port should not appear in DNS record, got:\n%s", content)
	}
	if !strings.Contains(content, "svc.example.com") {
		t.Errorf("expected hostname without port in output, got:\n%s", content)
	}
}
