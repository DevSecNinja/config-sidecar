package unbound_test

import (
	"strings"
	"testing"

	"github.com/home-operations/config-sidecar/internal/endpoint"
	unboundprovider "github.com/home-operations/config-sidecar/internal/provider/unbound"
)

func TestUnboundProvider_Name(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	if got := p.Name(); got != "unbound" {
		t.Errorf("Name() = %q, want %q", got, "unbound")
	}
}

func TestUnboundProvider_DefaultRecordType(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "", 0)
	if p.RecordType != "A" {
		t.Errorf("RecordType = %q, want %q", p.RecordType, "A")
	}
}

func TestUnboundProvider_Render_Empty(t *testing.T) {
	p := unboundprovider.New("192.168.1.1", "A", 0)
	data, err := p.Render(nil)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}
	// Should at least contain the generated comment.
	if !strings.Contains(string(data), "# Generated by sidecar") {
		t.Errorf("expected generated comment in output, got:\n%s", string(data))
	}
	// Should not contain any local-data entries.
	if strings.Contains(string(data), "local-data") {
		t.Errorf("expected no local-data entries for empty input, got:\n%s", string(data))
	}
}

func TestUnboundProvider_Render_SingleEndpoint(t *testing.T) {
	p := unboundprovider.New("192.168.1.100", "A", 0)
	endpoints := []*endpoint.Endpoint{
		{Name: "myapp", URL: "https://myapp.example.com", Interval: "1m"},
	}

	data, err := p.Render(endpoints)
	if err != nil {
		t.Fatalf("Render() error = %v", err)
	}

	content := string(data)
	if !strings.Contains(content, `local-data: "myapp.example.com. A 192.168.1.100"`) {
		t.Errorf("expected local-data record in output, got:\n%s", content)
	}
}

